-- Per-student lesson progress ("Continue learning" card + resume where you left off).
-- last_page / total_pages / pages_completed drive page-based progress for PDF e-books;
-- last_position_sec is the resume point for video/audio.
create table if not exists student_progress (
  progress_id bigint generated by default as identity primary key,
  student_id bigint not null references users(user_id) on delete cascade,
  material_id bigint not null references learning_materials(material_id) on delete cascade,
  completion_percentage integer not null default 0
    constraint student_progress_completion_percentage_range check (completion_percentage between 0 and 100),
  is_completed boolean not null default false,
  last_page integer default 1,
  total_pages integer default 0,
  pages_completed integer default 0,
  last_position_sec integer,
  duration_sec integer,
  last_accessed_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  constraint student_progress_student_material_key unique (student_id, material_id)
);

