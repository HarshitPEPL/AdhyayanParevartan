-- completion_percentage must be 0..100 (enforced for new writes right away; old rows are validated after).
do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.student_progress'::regclass
      and conname = 'student_progress_completion_percentage_range'
  ) then
    alter table student_progress
      add constraint student_progress_completion_percentage_range
      check (completion_percentage between 0 and 100) not valid;
  end if;
  begin
    alter table student_progress validate constraint student_progress_completion_percentage_range;
  exception when check_violation then
    raise notice 'Some existing rows have completion_percentage outside 0..100; fix them and re-run to validate the check.';
  end;
end $$;

-- Fast "most recently opened lesson" lookups.
create index if not exists student_progress_student_recent_idx
  on student_progress (student_id, last_accessed_at desc);

-- Keep updated_at fresh on every UPDATE.
create or replace function student_progress_set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

do $$
begin
  if not exists (
    select 1 from pg_trigger
    where tgrelid = 'public.student_progress'::regclass
      and tgname = 'student_progress_set_updated_at' and not tgisinternal
  ) then
    create trigger student_progress_set_updated_at
      before update on student_progress
      for each row execute function student_progress_set_updated_at();
  end if;
end $$;

-- RLS / access: mirrors the live project.
-- IMPORTANT: the app signs in with its own users table and only the anon key, so
-- auth.uid() is always NULL and these policies cannot be per-student. They are open
-- to every holder of the anon key (read, insert, update; no delete). Replace them with
-- per-student policies (e.g. student_id = (auth.jwt() ->> 'app_user_id')::bigint) once
-- logins are verified server-side (Edge Function + JWT or Supabase Auth).
alter table student_progress enable row level security;

do $$
begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'student_progress'
                 and policyname = 'Users can read own progress') then
    create policy "Users can read own progress" on student_progress for select to public using (true);
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'student_progress'
                 and policyname = 'Users can insert own progress') then
    create policy "Users can insert own progress" on student_progress for insert to public with check (true);
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'student_progress'
                 and policyname = 'student_progress_anon_update') then
    create policy student_progress_anon_update on student_progress for update to anon using (true) with check (true);
  end if;
end $$;

